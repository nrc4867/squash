package dev.chieppa.squash.schemagen.reference

import dev.chieppa.squash.character.build.AssemblyPart
import dev.chieppa.squash.character.build.TemplateLibrary
import dev.chieppa.squash.character.build.assembleNow
import dev.chieppa.squash.character.model.BodyPlan
import dev.chieppa.squash.character.model.PartTemplate
import dev.chieppa.squash.document.PairId
import dev.chieppa.squash.document.PartData
import dev.chieppa.squash.document.PartId
import dev.chieppa.squash.document.Side
import dev.chieppa.squash.document.SocketRef
import dev.chieppa.squash.document.TemplateId

/** How many sockets deep the undrawn character is filled. */
private const val DEPTH = 4

/**
 * Each plan's undrawn character, every plan and template socket filled with the first template it takes (or, for a socket taking any,
 * the template named after it) at its newest version and size 1, each part's box in body units above the ground: what a recipe's parts
 * measure before anything is drawn, so a first build's proportions can be set against them.
 */
internal object Proportions {
    fun render(templates: List<PartTemplate>, plans: List<BodyPlan>): String = buildString {
        appendLine("# Proportions")
        appendLine()
        appendLine("Generated by `generateSchemas`: each plan built undrawn, each part named for its template, the root and every socket the plan and its templates offer filled with the first template it takes (a socket taking any, as a head's `ear`, with the template named after it) at its newest version and `size` 1. Boxes are body units, x forward, y up from the ground under the lowest point, z to the character's right; a pair shows its left side. A drawn outline sets its own length and `size` scales a part, so these are where a first build starts: set a part's `size` or draw its outline against them. `tools/recipe.sh probe <recipe> part=all` prints the same for a built recipe.")
        val library = TemplateLibrary(templates, plans)
        val newest = templates.groupBy { it.id }.mapValues { (_, versions) -> versions.maxBy { it.version } }
        for (plan in plans.groupBy { it.id }.values.map { versions -> versions.maxBy { it.version } }.sortedBy { it.id.value }) {
            appendLine()
            appendLine("## ${plan.id.value} ${plan.version}")
            appendLine()
            val parts = partsOf(plan, newest)
            val built = assembleNow(parts, { PartData() }, plan, library)
            val floor = built.floor
            val rows = built.parts.mapNotNull { placed ->
                val box = placed.box ?: return@mapNotNull null
                listOf(
                    code(placed.id?.value ?: placed.template.id.value), code(placed.template.id.value), placed.socket?.let { code("${it.parent.value}.${it.socket}") } ?: "root",
                    num(box.size.x), num(box.size.y), num(box.size.z), num(box.low.y - floor), num(box.high.y - floor),
                )
            }
            append(table(listOf("part", "template", "on", "length x", "height y", "width z", "lowest y", "highest y"), rows))
            built.box?.let { appendLine(); appendLine("Whole: ${num(it.size.x)} long, ${num(it.size.y)} tall, ${num(it.size.z)} wide.") }
        }
    }

    private fun partsOf(plan: BodyPlan, newest: Map<TemplateId, PartTemplate>): List<AssemblyPart> {
        val root = newest[plan.root.template] ?: return emptyList()
        val parts = mutableListOf(AssemblyPart(PartId(plan.root.template.value), root.ref, null, null, null))
        fun fill(parent: PartId, template: PartTemplate, depth: Int) {
            if (depth >= DEPTH) return
            for (socket in plan.socketsOn(template)) {
                val child = (socket.takes.firstNotNullOfOrNull { newest[it] } ?: newest[TemplateId(socket.name)]) ?: continue
                val base = child.id.value.takeIf { name -> parts.none { it.id.value.removeSuffix("-l") == name } } ?: socket.name
                val id = PartId(if (socket.pair != null) "$base-l" else base)
                if (parts.any { it.id == id }) continue
                val pair = if (socket.pair != null) PairId(base) else null
                parts += AssemblyPart(id, child.ref, SocketRef(parent, socket.name), pair, if (pair != null) Side.LEFT else null)
                fill(id, child, depth + 1)
            }
        }
        fill(parts.first().id, root, 0)
        return parts
    }
}
