package dev.chieppa.squash.schemagen.reference

import dev.chieppa.squash.recipe.probe.bodyWords
import dev.chieppa.squash.character.block.Digits
import dev.chieppa.squash.character.build.sweeps
import dev.chieppa.squash.character.model.JointSpec
import dev.chieppa.squash.character.model.ParamSpec
import dev.chieppa.squash.character.model.PartTemplate
import dev.chieppa.squash.character.model.SectionSpec
import dev.chieppa.squash.character.model.SocketSpec
import dev.chieppa.squash.document.View
import dev.chieppa.squash.rig.BoneAngles
import dev.chieppa.squash.rig.hingeDirection

/** The template catalog: every template at its newest version, with the versions it replaced. */
internal object TemplateCatalog {
    fun render(templates: List<PartTemplate>): String = buildString {
        val byId = templates.groupBy { it.id.value }.toSortedMap()
        appendLine("# Templates")
        appendLine()
        appendLine(
            "Every template at its newest version, which a recipe part gets when it gives no `version`. Directions are the character's own: " +
                "forward, back, up, down, left, right (see frames.md). `u` runs 0 at the socket end to 1 at the tip; `v` runs round the part. " +
                "Lengths and radii are body units at `size` 1. A part's `curve` places or `spiral` give its axis's path on a template whose " +
                "`curve` column says yes, one that sweeps along its axis, drawn or not; any other template ignores them, with a warning. " +
                "Generated by `generateSchemas` from `templates/`.",
        )
        appendLine()
        append(
            table(
                listOf("template", "newest", "older versions", "name", "role", "curve"),
                byId.map { (id, all) ->
                    val newest = all.maxBy { it.version }
                    val older = all.map { it.version }.filter { it != newest.version }.sorted().joinToString().ifEmpty { "-" }
                    listOf(code(id), newest.version.toString(), older, newest.name, newest.role?.name?.lowercase() ?: "none (guessed from where it sits)", if (newest.sweeps) "yes" else "no")
                },
            ),
        )
        byId.values.forEach { all -> append(section(all.maxBy { it.version })) }
    }

    private fun section(template: PartTemplate): String = buildString {
        val frame = PartFrame(template)
        appendLine()
        appendLine("## ${template.id.value} ${template.version}")
        appendLine()
        append(table(listOf("fact", "value"), facts(template, frame).map { listOf(it.first, it.second) }))
        val sockets = template.blocks.flatMap { it.sockets() }
        if (sockets.isNotEmpty()) {
            appendLine()
            appendLine("Sockets:")
            appendLine()
            append(table(listOf("socket", "u", "v", "faces", "pair", "sink", "takes"), sockets.map { socketRow(it, frame) }))
        }
        val joints = template.blocks.flatMap { it.joints() }
        if (joints.isNotEmpty()) {
            appendLine()
            appendLine("Joints, which poses name; the move is for positive `degrees` on the left side at rest, the right side mirrors it:")
            appendLine()
            append(table(listOf("joint", "u", "hinge", "limits", "+degrees moves the tip"), joints.map { jointRow(it, frame) }))
        }
        template.blocks.filterIsInstance<Digits>().forEach { row -> append(digitJoints(template, row, frame)) }
        val patches = template.blocks.flatMap { it.patchNames() }
        if (patches.isNotEmpty()) {
            appendLine()
            appendLine("Patches: " + patches.joinToString { code(if (it.repeats) "${it.name}:<i>" else it.name) })
        }
        val areas = template.blocks.flatMap { it.areas(template.defaults) }
        if (areas.isNotEmpty()) {
            appendLine()
            appendLine("Paintable areas, filled with `\"areas\": {\"<area>\": \"<slot>\"}`:")
            appendLine()
            append(
                table(
                    listOf("area", "patch", "u", "v", "tag", "shown in slot"),
                    areas.map { listOf(code(it.name), it.patch, nums(it.u.start, it.u.end), nums(it.v.start, it.v.end), it.tag.name.lowercase(), it.color ?: "-") },
                ),
            )
        }
        val slots = template.blocks.flatMap { it.patchSlots() }
        if (slots.isNotEmpty()) {
            appendLine()
            appendLine("Patches shown in a palette slot of their own, coloured by naming that slot in the palette: " + slots.joinToString { "${code(it.patch)} in ${code(it.slot)}" })
        }
        val landmarks = template.blocks.flatMap { it.landmarks() }
        if (landmarks.isNotEmpty()) {
            appendLine()
            appendLine("Landmarks: " + landmarks.joinToString { "${code(it.name)} (u ${num(it.u)}, v ${num(it.v)})" })
        }
        if (template.params.isNotEmpty()) {
            appendLine()
            appendLine("Parameters:")
            appendLine()
            append(table(listOf("parameter", "default", "range", "meaning"), template.params.map { (name, spec) -> paramRow(name, spec) }))
        }
    }

    private fun facts(template: PartTemplate, frame: PartFrame): List<Pair<String, String>> {
        val rest = template.axis.rest
        val views = View.entries.joinToString("; ") { view -> "${view.name.lowercase()} sets ${template.views[view]?.name?.lowercase() ?: "nothing"}" }
        val section = when (val spec = template.section) {
            is SectionSpec.Named -> spec.profile.name.lowercase()
            else -> "drawn points"
        }
        return listOf(
            "rests" to "${bodyWords(frame.axes.along)} ${nums(rest.x, rest.y, rest.z)}",
            "outline x runs 0 to" to num(template.axis.length),
            "Side's +y faces" to bodyWords(frame.axes.up),
            "Top's +y faces" to bodyWords(frame.axes.side * -1f),
            "views" to views,
            "section" to section,
            "open end" to (template.openEnd?.name?.lowercase() ?: "none (closed)"),
            "surface" to template.surface.name.lowercase(),
        ) + listOfNotNull(
            template.mount?.let { "sits on its socket at" to "u ${num(it.u)}, v ${num(it.v)}" },
            template.axis.faces?.let { "face looks" to bodyWords(it.toVec3()) },
            template.join.blend?.let { "join blend" to "${num(it)} of its length, the skull or body rising into it; the part's `blend` overrides it" },
            template.join.ink.takeIf { !it }?.let { "join line" to "off unless the part sets `inkJoin`" },
            ("curve" to "takes `curve` and `spiral`: the path its axis follows, drawn outlines giving its width along it").takeIf { template.sweeps },
            template.generic?.let { "generic" to "rings ${it.rings.min} to ${it.rings.max}, segments ${it.segments.min} to ${it.segments.max}" },
        )
    }

    private fun socketRow(socket: SocketSpec, frame: PartFrame): List<String> = listOf(
        code(socket.name), num(socket.u), num(socket.v), frame.facing(socket.u, socket.v, socket.patch)?.let(::bodyWords) ?: "-",
        if (socket.pair != null) "yes" else "-", num(socket.sink), socket.takes.joinToString { it.value }.ifEmpty { "any" },
    )

    private fun jointRow(joint: JointSpec, frame: PartFrame): List<String> = listOf(
        code(joint.name), num(joint.u), joint.hinge.name.lowercase(), joint.limits?.let { nums(it.min, it.max) } ?: "none",
        tipMove(frame.axes.along, hingeDirection(joint.hinge, frame.axes, mirrored = false), BoneAngles(TEST_DEGREES, 0f, 0f)),
    )

    /**
     * The joints of [row]'s digits at the template's defaults, digit by digit, the move for positive degrees read along each digit's own
     * direction, with the counts and flags that change which digits it builds.
     */
    private fun digitJoints(template: PartTemplate, row: Digits, frame: PartFrame): String = buildString {
        val values = template.defaults
        val built = row.builtSegments(values)
        val chains = row.digitChains(built.map { it.first }.toSet()).associateBy { it.patch }
        if (chains.isEmpty()) return@buildString
        val counted = built.count { it.second.name == null }
        val named = built.mapNotNull { it.second.name }
        appendLine()
        appendLine(
            "Digit joints at the defaults, which poses name as `<patch>.<k>`, k from 1 at the digit's root: the row builds " +
                (if (counted == 1) "one counted digit" else "$counted counted digits") + ", numbered from 0" +
                (if (named.isEmpty()) "" else " (${named.joinToString { code(it) }} named apart, outside the numbers)") +
                (row.count?.let { "; parameter ${code(it.refName ?: it.raw)} sets how many" + if (row.countsNamed) ", the named digits that are on among them" else "" } ?: "") +
                ". Each patch is a digit sockets, regions and marks can name:",
        )
        appendLine()
        val rows = built.flatMap { (patch, digit) ->
            val chain = chains[patch] ?: return@flatMap emptyList()
            val d = digit.direction()
            val along = (frame.axes.along * d.x + frame.axes.up * d.y + frame.axes.side * d.z).normalized()
            chain.joints.map { joint ->
                listOf(
                    code(joint.name), code(patch), joint.hinge.name.lowercase(), joint.limits?.let { nums(it.min, it.max) } ?: "none",
                    tipMove(along, hingeDirection(joint.hinge, frame.axes, mirrored = false), BoneAngles(TEST_DEGREES, 0f, 0f)),
                )
            }
        }
        append(table(listOf("joint", "patch", "hinge", "limits", "+degrees moves the tip"), rows))
    }

    private fun paramRow(name: String, spec: ParamSpec): List<String> {
        val default = if (spec.default.isFlag) (if (spec.default.value != 0f) "1 (on)" else "0 (off)") else num(spec.default.value)
        val values = spec.values
        val range = when {
            spec.default.isFlag -> "a flag: 1 or 0"
            values != null -> "one of " + values.joinToString { num(it) }
            else -> listOfNotNull(spec.min?.let(::num), spec.max?.let(::num)).joinToString(" to ") + (spec.unit?.let { " $it" } ?: "")
        }
        return listOf(code(name), default, range, spec.doc ?: "-")
    }
}
