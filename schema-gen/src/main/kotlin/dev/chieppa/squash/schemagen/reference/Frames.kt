/** The test angle the reference turns a bone by to say which way it goes. */
internal const val TEST_DEGREES = 30f

/** A tip moving less than this has only rolled about its own length. */
private const val MOVED_LEAST = 1e-3f

/** Where round a part the frame table reads, and where along it. */
private val ROUND = listOf(0f, 0.25f, 0.5f, 0.75f)
private const val MIDDLE_U = 0.5f

/** The rest directions by the word a recipe's `rest` takes. */
internal fun restWord(rest: RestDirection): String = when (rest) {
    RestDirection.FORWARD -> "forward"
    RestDirection.BACK -> "back"
    RestDirection.UP -> "up"
    RestDirection.DOWN -> "down"
    RestDirection.OUT -> "out"
}

/** Where the tip of a bone along [along], hinged about [hinge], goes when [angles] turn it: toward which body direction. */
internal fun tipMove(along: Vec3, hinge: Vec3, angles: BoneAngles): String = move(along, along, hinge, angles)

/** Where [point], a direction from a bone along [along] hinged about [hinge], goes when [angles] turn it. */
private fun move(point: Vec3, along: Vec3, hinge: Vec3, angles: BoneAngles): String {
    val bone = Bone(BoneName(PartId("reference"), "joint"), null, Vec3.ZERO, along, 1f, hinge, null, false)
    val moved = localTurn(bone, angles) * point - point
    return if (moved.length < MOVED_LEAST) "stays" else bodyWords(moved)
}

/** The part frame and the bone axes, worked out by building a generic tube in each rest direction and turning its bone. */
internal object Frames {
    fun render(tube: PartTemplate): String = buildString {
        appendLine("# Frames")
        appendLine()
        appendLine("Generated by `generateSchemas` from the part builder and the rig. For any built recipe, `tools/recipe.sh probe` answers the same questions on its own parts.")
        appendLine()
        appendLine("## Body space")
        appendLine()
        append(
            table(
                listOf("axis", "points"),
                listOf(
                    listOf("+x", "forward, where the character faces"),
                    listOf("+y", "up"),
                    listOf("-z", "the character's left; +z its right"),
                    listOf("origin", "the root part's socket end; the ground is under the lowest point"),
                ),
            ),
        )
        appendLine()
        appendLine("A pair is described as its left side; its right side mirrors it across z = 0, and reads v as 1 - v.")
        appendLine("`reference=` compares use another frame: metres, +y up, the character facing +z with its left at +x.")
        appendLine("A face place `[x, y]` (regions, marks and eyes by `face`) is the head seen from straight ahead: x to the character's left, negative for its right, y up, in the head's drawn units from its socket.")
        appendLine()
        appendLine("## Part frame")
        appendLine()
        appendLine("By the direction a part rests in (a template's rest, or a recipe's `rest`), which way its outlines' y and its v run, at u ${num(MIDDLE_U)}. x of Side and Top runs along the part from its socket end. Front draws the section in -1 to 1: its x is Top's -y, its y Side's +y.")
        appendLine()
        append(
            table(
                listOf("rests") + listOf("Side's +y", "Top's +y") + ROUND.map { "v ${num(it)} faces" },
                RestDirection.entries.map { rest ->
                    val frame = PartFrame(tube, mapOf(PlacementParams.REST to rest.ordinal.toFloat()))
                    listOf(restWord(rest), bodyWords(frame.axes.up), bodyWords(frame.axes.side * -1f)) +
                        ROUND.map { v -> frame.facing(MIDDLE_U, v)?.let(::bodyWords) ?: "-" }
                },
            ),
        )
        appendLine()
        appendLine("## Bone axes")
        appendLine()
        appendLine("A pose bone `{\"part\", \"joint\", \"degrees\", \"lean\", \"turn\", \"twist\"}` on a part's joint, by the part's rest and the joint's hinge (a template joint's hinge is in templates.md; a recipe joint's is its `hinge`, x when left out). Each cell is where +${num(TEST_DEGREES)} of that angle alone moves the bone's tip, or for `turn` and `twist`, which only roll it, where its Side's +y goes. Negative angles move the other way. The right side of a pair takes the same numbers as a mirror image.")
        appendLine()
        val rows = RestDirection.entries.flatMap { rest ->
            val axes = PartFrame(tube, mapOf(PlacementParams.REST to rest.ordinal.toFloat())).axes
            Hinge.entries.map { hinge ->
                val axis = hingeDirection(hinge, axes, mirrored = false)
                listOf(
                    restWord(rest),
                    hinge.name.lowercase(),
                    tipMove(axes.along, axis, BoneAngles(TEST_DEGREES, 0f, 0f)),
                    tipMove(axes.along, axis, BoneAngles(0f, 0f, TEST_DEGREES)),
                    move(axes.up, axes.along, axis, BoneAngles(0f, TEST_DEGREES, 0f)),
                    move(axes.up, axes.along, axis, BoneAngles(0f, 0f, 0f, TEST_DEGREES)),
                )
            }
        }
        append(table(listOf("rests", "hinge", "+degrees: tip", "+lean: tip", "+turn: up", "+twist: up"), rows))
        appendLine()
        val down = PartFrame(tube, mapOf(PlacementParams.REST to RestDirection.DOWN.ordinal.toFloat())).axes
        val swing = tipMove(down.along, hingeDirection(Hinge.X, down, mirrored = false), BoneAngles(TEST_DEGREES, 0f, 0f))
        val out = tipMove(down.along, hingeDirection(Hinge.X, down, mirrored = false), BoneAngles(0f, 0f, TEST_DEGREES))
        appendLine("Worked example: a leg resting down, its `hip` on hinge x. `{\"part\": \"leg-l\", \"joint\": \"hip\", \"degrees\": ${num(TEST_DEGREES)}}` swings its foot $swing; `\"lean\": ${num(TEST_DEGREES)}` swings it $out, and on `leg-r` the same lean swings it the mirror way. A knee or elbow bends by `degrees` within its limits; `mode: \"free\"` lifts the limits. `twist` rolls a bone spread along its length (a forearm from elbow to wrist); `turn` rolls it whole.")
    }
}
