package dev.chieppa.squash.schemagen.reference

import dev.chieppa.squash.recipe.probe.bodyWords
import dev.chieppa.squash.character.model.BodyPlan
import dev.chieppa.squash.character.model.PartTemplate

/** The body plans: their root, sockets, slots and starting palette. */
internal object PlanCatalog {
    fun render(plans: List<BodyPlan>, templates: List<PartTemplate>): String = buildString {
        appendLine("# Plans")
        appendLine()
        appendLine(
            "A recipe's `plan` sets the root template and the sockets parts sit on, on top of each template's own sockets (templates.md). " +
                "The root is the recipe's first part. A socket with a pair takes a recipe pair. Generated by `generateSchemas` from `templates/plans/`.",
        )
        plans.groupBy { it.id.value }.toSortedMap().values.forEach { all ->
            val plan = all.maxBy { it.version }
            appendLine()
            appendLine("## ${plan.id.value} ${plan.version} (${plan.name})")
            appendLine()
            val rest = plan.root.rest
            append(
                table(
                    listOf("fact", "value"),
                    listOf(
                        listOf("root", "${code(plan.root.template.value)} resting ${bodyWords(rest.toVec3())} ${nums(rest.x, rest.y, rest.z)}"),
                        listOf("base slot", plan.base?.let(::code) ?: "-"),
                        listOf("palette", plan.palette.joinToString { code(it.name) }.ifEmpty { "-" }),
                    ),
                ),
            )
            if (plan.sockets.isNotEmpty()) {
                appendLine()
                append(
                    table(
                        listOf("socket", "on", "u", "v", "faces", "pair", "sink", "spread", "takes"),
                        plan.sockets.map { socket ->
                            val on = templates.filter { it.id == socket.on }.maxByOrNull { it.version }
                            val faces = on?.let { PartFrame(it).facing(socket.u, socket.v) }?.let(::bodyWords) ?: "-"
                            listOf(
                                code(socket.name), socket.on.value, num(socket.u), num(socket.v), faces, if (socket.pair != null) "yes" else "-",
                                num(socket.sink), num(socket.spread), socket.takes.joinToString { it.value },
                            )
                        },
                    ),
                )
            }
            if (plan.slots.isNotEmpty()) {
                appendLine()
                append(table(listOf("slot", "on", "takes", "default"), plan.slots.map { listOf(code(it.name), it.on.value, it.takes.joinToString { t -> t.value }, it.default?.value ?: "-") }))
            }
        }
    }
}
