package dev.chieppa.squash.schemagen.reference

import dev.chieppa.squash.character.load.TemplateFolder
import dev.chieppa.squash.document.TemplateId

/** The generic template the frame tables are worked out on. */
private val FRAME_TEMPLATE = TemplateId("tube")

/** The recipe author's reference under docs/reference/, generated from the shipped templates and the model so it cannot go stale. */
object Reference {
    /** Every reference file's name and text. */
    fun render(folder: TemplateFolder = TemplateFolder.shipped()): Map<String, String> {
        val tube = folder.parts.filter { it.id == FRAME_TEMPLATE }.maxBy { it.version }
        return mapOf(
            "README.md" to index(),
            "templates.md" to TemplateCatalog.render(folder.parts),
            "plans.md" to PlanCatalog.render(folder.plans, folder.parts),
            "proportions.md" to Proportions.render(folder.parts, folder.plans),
            "part-parameters.md" to PartParameters.render(),
            "frames.md" to Frames.render(tube),
            "face-and-clothes.md" to FaceAndClothes.render(folder.parts, folder.mouths, folder.teeth),
            "hair.md" to Hair.render(folder.parts),
        ).mapValues { (_, text) -> text.trimEnd() + "\n" }
    }

    private fun index(): String = buildString {
        appendLine("# Recipe reference")
        appendLine()
        appendLine("What a recipe can name, generated by `generateSchemas` from the code; a test fails when these files are stale. The recipe's own fields are described in `schema/recipe.schema.json`.")
        appendLine()
        append(
            table(
                listOf("file", "answers"),
                listOf(
                    listOf("templates.md", "each template's rest, outline length, what each view sets, sockets, joints with hinge and limits, areas, patches and parameters with meanings"),
                    listOf("plans.md", "each plan's root, sockets, slots and palette"),
                    listOf("proportions.md", "each plan built undrawn: every part's box and height above the ground at `size` 1, to set a first build's proportions against"),
                    listOf("part-parameters.md", "dotted part parameters (`move.*`, `socket.<n>.*`, `joint.<n>.*`, `curve.<n>.*`, `generic.*`, `join.ink`, `rig.reach.*`) and the recipe fields that write them"),
                    listOf("frames.md", "body space, which way u, v and each view's y run for a part resting each way, and which way `degrees`, `lean`, `turn` and `twist` move a bone"),
                    listOf("face-and-clothes.md", "mouth group roles and controls and how a mouth opens; region borders, corners and two-tone faces; how a painted eye faces and lands on its head, wrapped or flat, and every eye look field with its range and units; how garment fit, covers, redraws and swaps combine; head cheats that follow the camera, view keys"),
                    listOf("hair.md", "lock hair: every lock group field with its default, range and units; each kind, section and tip; each preset's groups and flow; the scalp flow's whorl, parting, sweep and cowlick fields; the fitted inner mass's parameters"),
                ),
            ),
        )
        appendLine()
        appendLine("For a built recipe, `tools/recipe.sh probe <recipe> ...` prints the same frame facts for its own parts: u and v at a body point or a face place, the body point at a u and v, and each part's extent, joints and sockets.")
        appendLine()
        appendLine("To write a recipe as a TypeScript character file, with typed helpers for a height plan, tube limbs, shapes, face marks, garments, props and palettes, see `kit/README.md`.")
    }
}
