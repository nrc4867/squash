/** What each mouth role holds. */
private fun roleMeaning(role: MarkRole): String = when (role) {
    MarkRole.INNER -> "the opening between the lips, filled with its `fill` slot while the mouth is open: its first mark, a closed shape drawn below the lip line, is the fully open mouth, closed toward the lip line as `open` falls; with no mark, a lower lip drops from the lip line by `open`, from nothing at the corners to 0.45 of the lip line's width at its middle"
    MarkRole.TONGUE -> "closed marks filled with its `fill` slot, carried down with the lower lip and kept between the lips; inked when the role's `ink` is"
    MarkRole.TEETH -> "closed marks filled with its `fill` slot, sharp at every place (a fang is three places), kept where drawn between the lips; inked when the role's `ink` is"
    MarkRole.LIP_LINE -> "the line of the closed mouth, drawn on the muzzle and wrapping round it; a group with one is a mouth"
    MarkRole.CORNERS -> "short marks at the mouth's ends"
}

private fun roleName(role: MarkRole) = when (role) {
    MarkRole.INNER -> "inner"
    MarkRole.TONGUE -> "tongue"
    MarkRole.TEETH -> "teeth"
    MarkRole.LIP_LINE -> "lipLine"
    MarkRole.CORNERS -> "corners"
}

/** Mouth groups, painted regions and how they meet, how a painted eye lies on its head, and how a garment's fit and its changes combine with the body. */
internal object FaceAndClothes {
    fun render(templates: List<PartTemplate>): String = buildString {
        appendLine("# Face and clothes")
        appendLine()
        appendLine("Generated by `generateSchemas` from the document model and the recipe schema's descriptions.")
        appendLine()
        appendLine("## Mouth group")
        appendLine()
        appendLine("A part's `groups` entry `{\"id\", \"name\", \"roles\": [{\"role\", \"marks\", \"fill\", \"ink\"}], \"controls\"}`. Roles draw in the order listed; a new mouth lists them in this order:")
        appendLine()
        val order = mouthGroup(MarkGroupId("mouth"), "Mouth").roles.map { it.role }
        append(table(listOf("draw", "role", "holds"), order.mapIndexed { i, role -> listOf((i + 1).toString(), code(roleName(role)), roleMeaning(role)) }))
        appendLine()
        appendLine("Each role's marks are mark ids on the same part. The opening, tongue and teeth show only while `open` is above 0, on any head: the lips part on the surface, and a head whose template has a `jaw` joint also drops it. The lower lip is inked as the lip line is.")
        appendLine()
        append(table(listOf("control", "meaning"), docs("controls", MarkControls.serializer().descriptor).map { listOf(it[0].removePrefix("controls "), it[1]) }))
        appendLine()
        appendLine("An expression's `open` (`{\"mouth\": 1}`) opens a group by id while that expression shows, in place of its `controls.open`; `tools/recipe.sh` renders each expression's face close-up as `<outfit>-face-<expression>.png`, and `set=head:mouth.open:1` (or `set=head:open:1` for a part's one mouth) tries a control without editing the recipe.")
        appendLine()
        appendLine("## Regions")
        appendLine()
        append(
            table(
                listOf("question", "answer"),
                listOf(
                    listOf("the shape of a border", "a smooth closed curve through its places, so four or five places make a round patch; with `curved: false`, straight between them on a part joined into the body's one surface, as a head on a neck"),
                    listOf("a sharp point in a border", "`corners`: indices into its places"),
                    listOf("a two-tone face", "a light region and a dark one whose borders pass through the same places along their boundary; they meet along one edge with no gap and no overlap, and turn sharply where the two borders part"),
                    listOf("which shows where two overlap", "the later in the part's `regions`"),
                    listOf("a region against the base colour", "its border alone, at any zoom"),
                ),
            ),
        )
        appendLine()
        append(table(listOf("field", "meaning"), docs("region", RecipeRegion.serializer().descriptor)))
        appendLine()
        appendLine("## Eyes")
        appendLine()
        append(
            table(
                listOf("question", "answer"),
                listOf(
                    listOf("where an eye's shapes are drawn", "in a plane square to its facing, through its middle, its chart running toward the head's front and top"),
                    listOf("which way an eye faces", "the surface's normal at its middle, turned out by the look's `lookOut`; with `flat`, the way the head faces, turned out likewise"),
                    listOf("how it lands on the head", "each point of the plane is carried along the facing onto the surface, so seen from its facing the eye reads as drawn"),
                    listOf("when to use `flat`", "a large eye on a small, round head, where facing the surface's normal follows the curve and the eye reads bent from the front"),
                ),
            ),
        )
        appendLine()
        append(table(listOf("field", "meaning"), docs("eye", RecipeEye.serializer().descriptor)))
        appendLine()
        appendLine("### Eye look")
        appendLine()
        appendLine(docOf(EyeLook.serializer().descriptor.annotations))
        appendLine()
        append(table(listOf("field", "default", "range", "meaning"), lookRows()))
        appendLine()
        appendLine("One unit of a look's lengths in body units, on each head template built undrawn at size 1, at its eye landmark; a drawn head scales them with its own size and shape. A round iris takes the irisRatio in the last column:")
        appendLine()
        append(table(listOf("head", "chart", "unit across", "unit down", "round iris's irisRatio"), EyeUnits.rows(templates)))
        appendLine()
        appendLine("## Garments")
        appendLine()
        append(
            table(
                listOf("question", "answer"),
                listOf(
                    listOf("what cloth is", "cells of each part's chart, 64 rows along the part (u) by 32 columns round it (v), a cell 1/64 of u by 1/32 of v; the cloth's edge is a smooth curve over the painted cells' edges, and paint under two cells wide drops out"),
                    listOf("areas or covers", "`areas` paint the cloth as Dress does, stroke by stroke; `covers` are the simple form, a box of cells each, painted into the first area; a garment may have both"),
                    listOf("what areas write", "with `areas`, `holes` or `tucks`, the parts covered and how far, the parts that come out through the cloth (a part on a socket inside the painted region and not painted itself), the tucked parts and the inked seams are read from the cells, as Dress writes them"),
                    listOf("a second colour", "a later area with its own `color`: a collar, cuffs or a waistband; where two areas meet the cloth stays one piece and the seam is inked with the hems"),
                    listOf("a curved hem or a side split", "paint the band, then a stroke with `unpaint` (an ellipse or lasso) over the hem where it should open or curve"),
                    listOf("which way v faces", "it depends on how the part rests; `tools/recipe.sh probe <recipe> part=<id>` prints where v 0, 0.25, 0.5 and 0.75 face"),
                    listOf("a sleeve or trouser leg", "paint the limb from u 0; its root rows meet the torso's cells, so the cloth runs on from the shoulder or hip in one piece"),
                    listOf("what a cover covers", "the cells of its part's 64 by 32 chart whose middles lie in its box, at least two rows and two columns; the hem follows those cells' edge, so a box edge moves by up to half a cell"),
                    listOf("a cover past its part's end", "`from` below 0 or `to` past 1 runs the cloth on past that end, where the cells reach it"),
                    listOf("how far a cover stands off its part", "the garment's `partFits` for that part, else its `fit`, else the cover's `ease`"),
                    listOf("where cloth stands off further", "a cover's Side and Top `outlines`, along the part's own x, add to that"),
                    listOf("what a `redraw` lays over the part", "outlines by view and parameters by key replace the part's; regions and marks replace by id, others kept; `color` replaces the base slot; `areas` by name"),
                    listOf("what a redraw starts from", "the bare part; with several garments worn, the outermost garment that changes the part wins, its change alone applied"),
                    listOf("what a `swap` does", "builds the part from the other template with only the swap's shape"),
                    listOf("a change on a pair", "named by the left side, it holds for both sides, mirrored"),
                    listOf("order of garments", "by `layer`, innermost first"),
                ),
            ),
        )
        appendLine()
        appendLine("Fields as the schema describes them:")
        appendLine()
        val rows = docs("garment", RecipeGarment.serializer().descriptor) + docs("area", RecipeArea.serializer().descriptor) +
            listOf(listOf("stroke", docOf(RecipeStroke.serializer().descriptor.annotations))) + docs("stroke", RecipeStroke.serializer().descriptor) + docs("hole", RecipeHole.serializer().descriptor) +
            docs("tuck", RecipeTuck.serializer().descriptor) + docs("cover", RecipeCover.serializer().descriptor) +
            listOf(
                listOf("change `hide`", docOf(RecipeChange.Hide.serializer().descriptor.annotations)),
                listOf("change `through`", docOf(RecipeChange.Through.serializer().descriptor.annotations)),
                listOf("change `redraw`", docOf(RecipeChange.Redraw.serializer().descriptor.annotations)),
                listOf("change `swap`", docOf(RecipeChange.Swap.serializer().descriptor.annotations)),
            )
        append(table(listOf("field", "meaning"), rows))
    }

    @OptIn(ExperimentalSerializationApi::class)
    private fun docs(owner: String, descriptor: SerialDescriptor): List<List<String>> = (0 until descriptor.elementsCount).mapNotNull { i ->
        val doc = descriptor.getElementAnnotations(i).filterIsInstance<Doc>().firstOrNull()?.text ?: return@mapNotNull null
        listOf("$owner ${code(descriptor.getElementName(i))}", doc)
    }

    /** Each eye look field with its default, its range and its meaning. */
    @OptIn(ExperimentalSerializationApi::class)
    private fun lookRows(): List<List<String>> {
        val descriptor = EyeLook.serializer().descriptor
        val defaults = Json { encodeDefaults = true }.encodeToJsonElement(EyeLook.serializer(), EyeLook()).jsonObject
        return (0 until descriptor.elementsCount).map { i ->
            val name = descriptor.getElementName(i)
            val annotations = descriptor.getElementAnnotations(i)
            val range = annotations.filterIsInstance<Range>().firstOrNull()?.let { "${num(it.min.toFloat())} to ${num(it.max.toFloat())}" } ?: "-"
            val default = defaults[name]?.let { if (it is JsonNull) "none" else it.toString().trim('"') } ?: "-"
            listOf(code(name), default, range, docOf(annotations))
        }
    }

    private fun docOf(annotations: List<Annotation>): String = annotations.filterIsInstance<Doc>().firstOrNull()?.text ?: "-"
}
