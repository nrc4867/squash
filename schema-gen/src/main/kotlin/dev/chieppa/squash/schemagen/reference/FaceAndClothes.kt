/** What each mouth role holds. */
private fun roleMeaning(role: MarkRole): String = when (role) {
    MarkRole.INNER -> "the shape between the lips, filled with its `fill` slot, shown as the mouth opens"
    MarkRole.TONGUE -> "marks clipped to the inner shape"
    MarkRole.TEETH -> "marks clipped to the inner shape"
    MarkRole.LIP_LINE -> "the line of the closed mouth, drawn on the muzzle and wrapping round it; a group with one is a mouth"
    MarkRole.CORNERS -> "short marks at the mouth's ends"
}

private fun roleName(role: MarkRole) = when (role) {
    MarkRole.INNER -> "inner"
    MarkRole.TONGUE -> "tongue"
    MarkRole.TEETH -> "teeth"
    MarkRole.LIP_LINE -> "lipLine"
    MarkRole.CORNERS -> "corners"
}

/** Mouth groups, painted regions and how they meet, how a painted eye lies on its head, and how a garment's fit and its changes combine with the body. */
internal object FaceAndClothes {
    fun render(): String = buildString {
        appendLine("# Face and clothes")
        appendLine()
        appendLine("Generated by `generateSchemas` from the document model and the recipe schema's descriptions.")
        appendLine()
        appendLine("## Mouth group")
        appendLine()
        appendLine("A part's `groups` entry `{\"id\", \"name\", \"roles\": [{\"role\", \"marks\", \"fill\", \"ink\"}], \"controls\"}`. Roles draw in the order listed; a new mouth lists them in this order:")
        appendLine()
        val order = mouthGroup(MarkGroupId("mouth"), "Mouth").roles.map { it.role }
        append(table(listOf("draw", "role", "holds"), order.mapIndexed { i, role -> listOf((i + 1).toString(), code(roleName(role)), roleMeaning(role)) }))
        appendLine()
        appendLine("`controls`: `open` 0 closed to 1 open (drives the jaw joint and parts the lips), `width` scales it across, `mouthShape` (" + MouthShape.entries.joinToString { code(it.name) } + ") bends the lip line, `expressionBlend` 0 at the group's own marks to 1 at the shown expression's. Each role's marks are mark ids on the same part.")
        appendLine()
        appendLine("## Regions")
        appendLine()
        append(
            table(
                listOf("question", "answer"),
                listOf(
                    listOf("the shape of a border", "a smooth closed curve through its places, so four or five places make a round patch; with `curved: false`, straight between them on a part joined into the body's one surface, as a head on a neck"),
                    listOf("a sharp point in a border", "`corners`: indices into its places"),
                    listOf("a two-tone face", "a light region and a dark one whose borders pass through the same places along their boundary; they meet along one edge with no gap and no overlap, and turn sharply where the two borders part"),
                    listOf("which shows where two overlap", "the later in the part's `regions`"),
                    listOf("a region against the base colour", "its border alone, at any zoom"),
                ),
            ),
        )
        appendLine()
        append(table(listOf("field", "meaning"), docs("region", RecipeRegion.serializer().descriptor)))
        appendLine()
        appendLine("## Eyes")
        appendLine()
        append(
            table(
                listOf("question", "answer"),
                listOf(
                    listOf("where an eye's shapes are drawn", "in a plane square to its facing, through its middle, its chart running toward the head's front and top"),
                    listOf("which way an eye faces", "the surface's normal at its middle, turned out by the look's `lookOut`; with `flat`, the way the head faces, turned out likewise"),
                    listOf("how it lands on the head", "each point of the plane is carried along the facing onto the surface, so seen from its facing the eye reads as drawn"),
                    listOf("when to use `flat`", "a large eye on a small, round head, where facing the surface's normal follows the curve and the eye reads bent from the front"),
                ),
            ),
        )
        appendLine()
        append(table(listOf("field", "meaning"), docs("eye", RecipeEye.serializer().descriptor)))
        appendLine()
        appendLine("## Garments")
        appendLine()
        append(
            table(
                listOf("question", "answer"),
                listOf(
                    listOf("what a cover covers", "the cells of its part's 64 by 32 chart whose middles lie in its box, at least two rows and two columns; the hem follows those cells' edge, so a box edge moves by up to half a cell"),
                    listOf("a cover past its part's end", "`from` below 0 or `to` past 1 runs the cloth on past that end, where the cells reach it"),
                    listOf("how far a cover stands off its part", "the garment's `partFits` for that part, else its `fit`, else the cover's `ease`"),
                    listOf("where cloth stands off further", "a cover's Side and Top `outlines`, along the part's own x, add to that"),
                    listOf("what a `redraw` lays over the part", "outlines by view and parameters by key replace the part's; regions and marks replace by id, others kept; `color` replaces the base slot; `areas` by name"),
                    listOf("what a redraw starts from", "the bare part; with several garments worn, the outermost garment that changes the part wins, its change alone applied"),
                    listOf("what a `swap` does", "builds the part from the other template with only the swap's shape"),
                    listOf("a change on a pair", "named by the left side, it holds for both sides, mirrored"),
                    listOf("order of garments", "by `layer`, innermost first"),
                ),
            ),
        )
        appendLine()
        appendLine("Fields as the schema describes them:")
        appendLine()
        val rows = docs("garment", RecipeGarment.serializer().descriptor) + docs("cover", RecipeCover.serializer().descriptor) +
            listOf(
                listOf("change `hide`", docOf(RecipeChange.Hide.serializer().descriptor.annotations)),
                listOf("change `through`", docOf(RecipeChange.Through.serializer().descriptor.annotations)),
                listOf("change `redraw`", docOf(RecipeChange.Redraw.serializer().descriptor.annotations)),
                listOf("change `swap`", docOf(RecipeChange.Swap.serializer().descriptor.annotations)),
            )
        append(table(listOf("field", "meaning"), rows))
    }

    @OptIn(ExperimentalSerializationApi::class)
    private fun docs(owner: String, descriptor: SerialDescriptor): List<List<String>> = (0 until descriptor.elementsCount).mapNotNull { i ->
        val doc = descriptor.getElementAnnotations(i).filterIsInstance<Doc>().firstOrNull()?.text ?: return@mapNotNull null
        listOf("$owner ${code(descriptor.getElementName(i))}", doc)
    }

    private fun docOf(annotations: List<Annotation>): String = annotations.filterIsInstance<Doc>().firstOrNull()?.text ?: "-"
}
