/** What each mouth role holds. */
private fun roleMeaning(role: MarkRole): String = when (role) {
    MarkRole.INNER -> "the opening between the lips, filled with its `fill` slot while the lips part: its first mark, a closed shape drawn below the lip line, is the fully open mouth, closed toward the upper lip as `open` falls; with no mark, a lower lip drops from the upper lip by `open`, from nothing at the corners to the style's `depth` of the lip line's width at its middle"
    MarkRole.TONGUE -> "closed marks filled with its `fill` slot, drawn where they sit in a fully open mouth, riding the lower lip and kept between the lips; `tongue` lifts them to the upper teeth, then out past the lower lip, over it; with a `fill` and no mark, a plain tongue shows once `tongue` is above 0; inked when the role's `ink` is"
    MarkRole.TEETH -> "closed marks filled with its `fill` slot, sharp at every place (a fang is three places): a tooth reaching the lip line rides the upper lip, one below it rides the jaw as drawn in a fully open mouth; kept between the lips, or with its id in `over` drawn over them, open or shut, breaking the lip ink; inked when the role's `ink` is"
    MarkRole.LIP_LINE -> "the line of the closed mouth, drawn on the muzzle and wrapping round it, which the controls shape into an upper lip and a lower lip; a group with one is a mouth"
    MarkRole.CORNERS -> "short marks at the mouth's ends"
}

private fun roleName(role: MarkRole) = when (role) {
    MarkRole.INNER -> "inner"
    MarkRole.TONGUE -> "tongue"
    MarkRole.TEETH -> "teeth"
    MarkRole.LIP_LINE -> "lipLine"
    MarkRole.CORNERS -> "corners"
}

