    /** The recipe's `viewKeys`: what each view moves on a head and how its face follows the camera. */
    private fun StringBuilder.viewKeys() {
        appendLine("## View keys")
        appendLine()
        appendLine(
            "A recipe's `viewKeys`: head cheats that follow the camera. Squash builds each head once at eight directions round its own facing " +
                "(front, three-quarter, side and three-quarter back on either side, and back) on the surface it already has, and blends the two " +
                "nearest as the camera turns, so the head's paint, eyes and ink marks ride on it. Which keys hold is read from where the camera sits " +
                "round the head's own facing, so a head turned over the shoulder picks its keys by where it points. Keys are written as seen with the " +
                "camera on the head's left; for the right Squash mirrors them, a paired part's move going to its twin, unless a key names `side`.",
        )
        appendLine()
        appendLine(
            "With `auto` every head has defaults: its muzzle leans toward the camera, its ears turn toward profile, its back is drawn a little " +
                "wider and lower, and, in the turning face style, its near cheek fills out and its chin slides toward the camera. Its face follows " +
                "the camera as far as its style says, sliding back to hide behind the head past the side view.",
        )
        appendLine()
        val rows = docs("viewKeys", ViewKeys.serializer().descriptor) + docs("key", ViewKey.serializer().descriptor) + docs("move", KeyMove.serializer().descriptor)
        append(table(listOf("field", "meaning"), rows))
    }

    @OptIn(ExperimentalSerializationApi::class)
    private fun docs(owner: String, descriptor: SerialDescriptor): List<List<String>> = (0 until descriptor.elementsCount).mapNotNull { i ->
        val doc = descriptor.getElementAnnotations(i).filterIsInstance<Doc>().firstOrNull()?.text ?: return@mapNotNull null
        listOf("$owner ${code(descriptor.getElementName(i))}", doc)
    }

    /** A detail group's heading, its meaning and its fields' table. */
    @OptIn(ExperimentalSerializationApi::class)
    private fun <T> StringBuilder.detailTable(name: String, serializer: KSerializer<T>, defaults: T) {
        appendLine("#### ${code(name)}")
        appendLine()
        appendLine(docOf(serializer.descriptor.annotations))
        appendLine()
        append(table(listOf("field", "default", "range", "meaning"), lookRows(serializer, defaults)))
        appendLine()
    }

    /** Each field of [serializer]'s type with its default in [defaults], its range and its meaning; a nested group's default is `off`. */
    @OptIn(ExperimentalSerializationApi::class)
    private fun <T> lookRows(serializer: KSerializer<T>, defaults: T): List<List<String>> {
        val descriptor = serializer.descriptor
        val values = Json { encodeDefaults = true }.encodeToJsonElement(serializer, defaults).jsonObject
        return (0 until descriptor.elementsCount).map { i ->
            val name = descriptor.getElementName(i)
            val annotations = descriptor.getElementAnnotations(i)
            val range = annotations.filterIsInstance<Range>().firstOrNull()?.let { "${num(it.min.toFloat())} to ${num(it.max.toFloat())}" } ?: "-"
            val default = values[name]?.let {
                when (it) {
                    is JsonNull -> "none"
                    is JsonObject -> "off"
                    else -> it.toString().trim('"')
                }
            } ?: "-"
            listOf(code(name), default, range, docOf(annotations))
        }
    }

    private fun docOf(annotations: List<Annotation>): String = annotations.filterIsInstance<Doc>().firstOrNull()?.text ?: "-"
}
